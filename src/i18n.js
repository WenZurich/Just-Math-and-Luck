const ENUM_TOKEN_RE =
  /\b(euphoric|late_optimism|mid_cycle|cautious_recovery|despondent|panic|defensive|selective|balanced|constructive|aggressive|stabilize_first|risk_off|risk_on|neutral)\b/g;

/** Localized label for regime/phase/stance/liquidity enums — never leave snake_case in UI. */
export function enumLabel(value) {
  if (value == null || value === "") return t("dataInsufficient");
  const raw = String(value);
  const key = `enum_${raw}`;
  const human = raw.includes("_") ? raw.replace(/_/g, " ") : raw;
  return t(key, human.replace(/\b\w/g, (c) => c.toUpperCase()));
}

/** CSS tone key for stance badges (hyphenated). */
export function stanceTone(stance) {
  const s = String(stance || "").toLowerCase();
  const known = [
    "defensive",
    "selective",
    "balanced",
    "constructive",
    "aggressive",
    "stabilize_first",
  ];
  if (!known.includes(s)) return "neutral";
  return s.replace(/_/g, "-");
}

/** Replace known enum tokens inside free-text implications / notes. */
export function humanizeEnumsInText(text) {
  if (text == null || text === "") return "";
  return String(text).replace(ENUM_TOKEN_RE, (m) => enumLabel(m));
}

/**
 * @param {string} key
 * @param {string|Record<string,string|number>} [fallbackOrParams]
 * @param {Record<string,string|number>} [params]
 */
export function t(key, fallbackOrParams, params) {
  let fallback;
  let p = params;
  if (fallbackOrParams && typeof fallbackOrParams === "object" && !Array.isArray(fallbackOrParams)) {
    p = fallbackOrParams;
  } else if (typeof fallbackOrParams === "string") {
    fallback = fallbackOrParams;
  }
  const dict = STRINGS[current] || STRINGS[DEFAULT_LANG];
  let s = dict[key] ?? STRINGS[DEFAULT_LANG][key] ?? fallback ?? key;
  if (p) {
    for (const [k, v] of Object.entries(p)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return s;
}

export function renderLangSwitcher() {
  const opts = LANGS.map(
    (l) =>
      `<option value="${l.id}"${l.id === current ? " selected" : ""}>${l.label}</option>`
  ).join("");
  return `
    <label class="lang-switch" title="${t("langLabel")}">
      <span class="lang-switch-label">${t("langLabel")}</span>
      <select class="lang-select" data-lang-select aria-label="${t("langLabel")}">
        ${opts}
      </select>
    </label>`;
}

export function bindLangSwitcher(root, onChange) {
  const sel = root?.querySelector?.("[data-lang-select]");
  if (!sel) return;
  sel.value = current;
  sel.addEventListener("change", () => {
    if (setLang(sel.value) && typeof onChange === "function") onChange(sel.value);
  });
}
