/**
 * Site i18n — chrome strings. Persist in localStorage (`site-lang`).
 * Dynamic JSON (company names, strategy condition text) may stay as-is.
 */

export const LANGS = [
  { id: "zh-Hant", label: "繁體中文", short: "繁" },
  { id: "en", label: "English", short: "EN" },
  { id: "zh-Hans", label: "简体中文", short: "简" },
  { id: "ja", label: "日本語", short: "日" },
];

export const LANG_IDS = LANGS.map((l) => l.id);
const STORAGE_KEY = "site-lang";
const DEFAULT_LANG = "zh-Hant";

const listeners = new Set();

function detectInitial() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && LANG_IDS.includes(saved)) return saved;
  } catch {
    /* ignore */
  }
  const nav = (typeof navigator !== "undefined" && navigator.language) || "";
  if (/^zh[-_]?(CN|Hans|SG)/i.test(nav)) return "zh-Hans";
  if (/^zh/i.test(nav)) return "zh-Hant";
  if (/^ja/i.test(nav)) return "ja";
  if (/^en/i.test(nav)) return "en";
  return DEFAULT_LANG;
}

let current = detectInitial();

export function getLang() {
  return current;
}

export function setLang(lang) {
  if (!LANG_IDS.includes(lang) || lang === current) return false;
  current = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* ignore */
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = lang === "zh-Hant" ? "zh-Hant" : lang === "zh-Hans" ? "zh-Hans" : lang;
  }
  listeners.forEach((fn) => {
    try {
      fn(lang);
    } catch {
      /* ignore */
    }
  });
  return true;
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** BCP47 for Number/Date locale */
export function numberLocale() {
  if (current === "en") return "en-US";
  if (current === "ja") return "ja-JP";
  if (current === "zh-Hans") return "zh-CN";
  return "zh-TW";
}

export function applyDocumentLang() {
  if (typeof document === "undefined") return;
  document.documentElement.lang =
    current === "zh-Hant" ? "zh-Hant" : current === "zh-Hans" ? "zh-Hans" : current;
}

